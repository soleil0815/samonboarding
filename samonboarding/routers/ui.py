"""UI: HTML page and static files (local Tailwind CSS, fonts Manrope/JetBrains Mono, Font Awesome).

Everything is served from our own server - there are no connections to CDNs or Google Fonts.
"""

import html
import json
import logging

from fastapi import APIRouter, FastAPI
from fastapi.responses import HTMLResponse, Response
from fastapi.staticfiles import StaticFiles

from .. import i18n
from ..config import CONFIG_FILE, STATIC_DIR, VERSION, WEB_DIR, default_config
from ..storage import load_json

log = logging.getLogger(__name__)
router = APIRouter()

LOCAL_ASSETS = ("app.css", "vendor/fonts/fonts.css", "vendor/fontawesome/css/all.min.css")


# Without the Docker build the files are missing. Nothing is loaded from the internet anyway;
# instead a clear notice appears at the top of the page.
MISSING_ASSETS_HINT = """<style>
        body::before { content: "SAMONBOARDING: CSS/Schriften fehlen (static/). Bitte das Docker-Image neu bauen: docker compose up -d --build";
            display: block; padding: 12px 16px; background: #b91c1c; color: #fff; font: 600 14px system-ui, sans-serif; }
    </style>"""


def asset_head():
    """HTML head tags for CSS/fonts - always local from /static, never from the internet."""
    links = "\n    ".join(
        f'<link rel="stylesheet" href="/static/{name}?v={VERSION}">'
        for name in ("vendor/fonts/fonts.css", "vendor/fontawesome/css/all.min.css", "app.css")
    )
    if all((STATIC_DIR / name).is_file() for name in LOCAL_ASSETS):
        return links
    log.error("Lokale Assets in %s fehlen - Docker-Image neu bauen (docker compose up -d --build)", STATIC_DIR)
    return links + "\n    " + MISSING_ASSETS_HINT


def mount_static(app: FastAPI):
    """Mounts /static (CSS, fonts, icons generated by the Docker build), if present."""
    if STATIC_DIR.is_dir():
        app.mount("/static", StaticFiles(directory=str(STATIC_DIR)), name="static")


_file_cache = {}


def _load_web_file(name):
    """Reads a file from samonboarding/web; re-read only when the file changes."""
    path = WEB_DIR / name
    mtime = path.stat().st_mtime_ns
    cached = _file_cache.get(name)
    if not cached or cached[0] != mtime:
        cached = (mtime, path.read_text(encoding="utf-8"))
        _file_cache[name] = cached
    return cached[1]


def load_index_html():
    return _load_web_file("index.html")


def load_app_js():
    return _load_web_file("app.js")


def i18n_json():
    """Dictionary for the English UI (embedded, '</' escaped)."""
    return json.dumps(i18n.dictionary(), ensure_ascii=False).replace("</", "<\\/")


@router.get("/app.js")
def serve_app_js():
    """The interface logic as its own file, so the CSP can forbid inline scripts. The page links it with
    ?v=<version>: it may be kept for a day, an update changes the address."""
    return Response(
        load_app_js().replace("__APP_VERSION__", VERSION),
        media_type="text/javascript; charset=utf-8",
        headers={"Cache-Control": "public, max-age=86400"},
    )


@router.get("/", response_class=HTMLResponse)
def serve_gui():
    cfg = load_json(CONFIG_FILE, default_config)
    domain = html.escape(str(cfg.get("domain", "firma.local")))
    return (
        load_index_html()
        .replace("__ASSET_HEAD__", asset_head())
        .replace("__APP_VERSION__", VERSION)
        .replace("__APP_DOMAIN__", domain)
        .replace("__I18N__", i18n_json())
    )
